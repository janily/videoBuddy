// End-to-end: 4 shots x 72 frames (3s @24fps) at 1920x1080.
// CURRENT: per shot PNG files -> ffmpeg(lanczos, x264 medium); concat re-encode crf18; drawtext re-encode.
// PROPOSED: one browser, per shot JPEG piped to ffmpeg (label overlay in same encode); concat -c copy + metadata.
import {chromium} from 'playwright';
import {spawn} from 'node:child_process';import {readFileSync,mkdirSync,rmSync,writeFileSync} from 'node:fs';
const SHOTS=4,N=72,fps=24,html=readFileSync('scene.html','utf8'),font='/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc';
const run=(args,stdin)=>new Promise((res,rej)=>{const p=spawn('ffmpeg',['-hide_banner','-loglevel','error','-y',...args],{stdio:[stdin?'pipe':'ignore','inherit','inherit']});p.on('close',c=>c===0?res():rej(Error('ffmpeg '+c)));if(stdin)stdin(p)});
const x264=['-c:v','libx264','-threads','2','-pix_fmt','yuv420p','-color_primaries','bt709','-color_trc','bt709','-colorspace','bt709'];
const label=`drawtext=fontfile=${font}:text=AI生成:fontcolor=white@0.85:fontsize=h*0.026:box=1:boxcolor=black@0.32:boxborderw=10:x=w-tw-w*0.03:y=h*0.03`;
rmSync('out',{recursive:true,force:true});mkdirSync('out');
const out={};
// CURRENT
let t0=Date.now(),tCapture=0;
for(let s=0;s<SHOTS;s++){
 const browser=await chromium.launch({args:['--no-sandbox','--disable-dev-shm-usage']}); // a fresh container+browser per shot today
 const page=await browser.newPage({viewport:{width:1920,height:1080}});await page.setContent(html);
 mkdirSync(`out/f${s}`);const c0=Date.now();
 for(let f=0;f<N;f++){await page.evaluate(t=>window.render(t),(s*N+f)/fps);await page.screenshot({path:`out/f${s}/${String(f).padStart(6,'0')}.png`,animations:'disabled'})}
 tCapture+=Date.now()-c0;await browser.close();
 await run(['-threads','2','-framerate',String(fps),'-i',`out/f${s}/%06d.png`,'-vf','scale=1920:1080:flags=lanczos',...x264,'-movflags','+faststart',`out/cur${s}.mp4`]);
}
out.current_shots_ms=Date.now()-t0;out.current_capture_ms=tCapture;
let t1=Date.now();
await run([...Array.from({length:SHOTS},(_,i)=>['-i',`out/cur${i}.mp4`]).flat(),'-filter_complex',Array.from({length:SHOTS},(_,i)=>`[${i}:v]`).join('')+`concat=n=${SHOTS}:v=1:a=0[v]`,'-map','[v]','-preset','medium','-crf','18',...x264,'-movflags','+faststart','out/cur_seq.mp4']);
out.current_concat_ms=Date.now()-t1;t1=Date.now();
await run(['-i','out/cur_seq.mp4','-f','lavfi','-t',String(SHOTS*N/fps),'-i','anullsrc=r=48000:cl=stereo','-filter_complex',`[0:v]${label}[v]`,'-map','[v]','-map','1:a',...x264,'-c:a','aac','-shortest','-metadata','aigc=AIGC: generated by VideoBuddy','-movflags','+faststart','out/cur_final.mp4']);
out.current_compose_ms=Date.now()-t1;out.current_total_ms=Date.now()-t0;
// PROPOSED
t0=Date.now();tCapture=0;
const browser=await chromium.launch({args:['--no-sandbox','--disable-dev-shm-usage']});
for(let s=0;s<SHOTS;s++){
 const ctx=await browser.newContext({viewport:{width:1920,height:1080}}),page=await ctx.newPage();await page.setContent(html);
 const c0=Date.now();
 await run(['-f','image2pipe','-c:v','mjpeg','-framerate',String(fps),'-i','-','-vf',label,...x264,'-preset','veryfast','-crf','18','-g',String(fps*2),'-movflags','+faststart',`out/new${s}.mp4`],async p=>{
  for(let f=0;f<N;f++){await page.evaluate(t=>window.render(t),(s*N+f)/fps);const buf=await page.screenshot({type:'jpeg',quality:92,animations:'disabled'});if(!p.stdin.write(buf))await new Promise(r=>p.stdin.once('drain',r))}
  p.stdin.end();
 });
 tCapture+=Date.now()-c0;await ctx.close();
}
await browser.close();
out.proposed_shots_ms=Date.now()-t0;
t1=Date.now();
writeFileSync('out/list.txt',Array.from({length:SHOTS},(_,i)=>`file 'new${i}.mp4'`).join('\n'));
await run(['-f','concat','-safe','0','-i','out/list.txt','-f','lavfi','-t',String(SHOTS*N/fps),'-i','anullsrc=r=48000:cl=stereo','-map','0:v','-map','1:a','-c:v','copy','-c:a','aac','-shortest','-metadata','aigc=AIGC: generated by VideoBuddy','-movflags','+faststart','out/new_final.mp4']);
out.proposed_assemble_ms=Date.now()-t1;out.proposed_total_ms=Date.now()-t0;
// frame count check
const probe=f=>new Promise(r=>{const p=spawn('ffprobe',['-v','error','-count_frames','-select_streams','v:0','-show_entries','stream=nb_read_frames','-of','csv=p=0',f]);let o='';p.stdout.on('data',d=>o+=d);p.on('close',()=>r(o.trim()))});
out.frames_current=await probe('out/cur_final.mp4');out.frames_proposed=await probe('out/new_final.mp4');
console.log(JSON.stringify(out,null,1));
